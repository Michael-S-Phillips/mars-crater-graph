"""Calibration test of the sequence model on synthetic crater clusters.

  python scripts/test_sequence_model.py

Clusters of 2-7 craters are generated by the impact-arrival process the model
assumes: the oldest crater's crater time is drawn from a log-normal population,
and each later crater is uniform between zero and the youngest of the one or two
craters it superposes. Counts are Poisson with exposures of 30-3,000 km^2. The
script reports how often the 68% and 95% posterior intervals contain the true
crater time, for the impact-arrival prior and for independent population priors.
"""
import os, sys
import numpy as np
import networkx as nx
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from mcgraph.chronology import tau_grid, log_lik, fit_prior, gibbs_arrival, gibbs

rng = np.random.default_rng(2)
grid = tau_grid()
tau, edges, n = [], [], 0
for _ in range(700):
    m = rng.integers(2, 8)
    t = np.zeros(m)
    t[0] = np.exp(rng.normal(np.log(8e-3), 0.5))
    for j in range(1, m):
        ps = rng.choice(j, 1 if (rng.random() < 0.8 or j == 1) else 2, replace=False)
        t[j] = rng.uniform(0, min(t[p] for p in ps))
        edges += [(n + p, n + j) for p in ps]
    tau += list(t); n += m
tau = np.clip(np.array(tau), grid[0], grid[-1])
g = nx.DiGraph(); g.add_edges_from(edges)
edges = np.array(list(nx.transitive_reduction(g).edges()))
L = np.exp(rng.uniform(np.log(30), np.log(3000), n))
k = rng.poisson(tau * L)
LL = log_lik(k, L, grid)
lg = np.log(grid)
g_true = np.exp(-0.5 * ((lg - np.log(8e-3)) / 0.5) ** 2) * np.gradient(lg); g_true /= g_true.sum()
S = grid[gibbs_arrival(LL, np.log(g_true), edges, grid, n_sweeps=3000, burn=500)]
S2 = grid[gibbs(LL + np.log(fit_prior(LL) + 1e-300)[None, :], edges, n_sweeps=2000, burn=300)]
print(f"{n} craters in 700 clusters, {len(edges)} relations")
for name, s in (("impact-arrival prior", S), ("independent population priors", S2)):
    cov = [np.mean((tau >= np.quantile(s, a, 0)) & (tau <= np.quantile(s, b, 0)))
           for a, b in ((0.16, 0.84), (0.025, 0.975))]
    print(f"{name}: 68% intervals cover {cov[0]:.1%}, 95% intervals cover {cov[1]:.1%}")
